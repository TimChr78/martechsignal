#!/usr/bin/env python3
"""Normalize page chrome across every HTML file on disk.

Builders emit the new shared chrome from tools/site_chrome.py, but the repo also
contains hand-authored pages the builders never rewrite. This pass makes the
same contract true for them and is safe to run on every deploy: a second run
must report zero changes.

Run after the builders (deploy.sh wires it after sync_breadcrumbs.py).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from site_chrome import HEAD_TAGS, chrome_footer, chrome_top

SKIP_DIRS = {"deploy-out", "node_modules", "design", ".git"}

OLD_PRELOADS_ALWAYS = re.compile(
    r'[ \t]*<link rel="preload" href="/fonts/(?:archivo-black-400|spline-sans-mono-[^"]*)\.woff2"[^>]*>\n?'
)
OLD_PRELOADS_WITH_ARCHIVO = re.compile(
    r'[ \t]*<link rel="preload" href="/fonts/(?:archivo-black-400|spline-sans-mono-[^"]*|archivo-var)\.woff2"[^>]*>\n?'
)
DECORATION_DIV = re.compile(
    r'[ \t]*<div class="(?:bg|dot-grid|glow[^"]*)"[^>]*>\s*</div>\n?'
)
PULSE_DOT = re.compile(r'[ \t]*<span class="pulse-dot"[^>]*>\s*</span>')
# Hand-authored pages still carry the pre-redesign critical bundle inline. It
# pins Archivo Black/Spline and overrides the new stylesheet, so drop the whole
# block; the shared stylesheet is the single source of design now.
LEGACY_STYLE_BLOCK = re.compile(
    r'<style[^>]*>(?:(?!</style>)[\s\S])*?(?:Archivo Black|Spline Sans Mono)(?:(?!</style>)[\s\S])*?</style>\n?'
)
PULSE_RULE = re.compile(r'[ \t]*\.pulse-dot[^{}]*\{[^}]*\}[ \t]*\n?')

# The shared critical bundle is generated by build_tools before this sweep runs.
# Pages built before the critical file was regenerated (build_hubs runs first)
# or hand-authored pages can carry the old bundle or none at all.
try:
    CRITICAL_CSS = (ROOT / "tools" / ".critical.css").read_text().strip()
except OSError:
    CRITICAL_CSS = ""
if "Archivo Black" in CRITICAL_CSS or "Spline Sans Mono" in CRITICAL_CSS:
    CRITICAL_CSS = ""


def url_path(path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    if rel.endswith("/index.html"):
        return "/" + rel[:-len("index.html")]
    if rel == "index.html":
        return "/"
    return "/" + rel


def insert_head_tags(head: str) -> str:
    if "/theme.js" not in head:
        head = OLD_PRELOADS_WITH_ARCHIVO.sub("", head)
        candidates = [m.start() for m in re.finditer(
            r'<style\b|<link\b[^>]*rel=["\']stylesheet["\']', head, re.I)]
        at = candidates[0] if candidates else len(head)
        head = head[:at] + HEAD_TAGS + "\n" + head[at:]
    else:
        # Keep the HEAD_TAGS archivo preload; only retired fonts go.
        head = OLD_PRELOADS_ALWAYS.sub("", head)
    return head


def ensure_critical(text: str) -> str:
    """Keep exactly one current inline critical bundle per page (M1 contract)."""
    if not CRITICAL_CSS:
        return text
    blocks = list(re.finditer(r'<style[^>]*>([\s\S]*?)</style>', text))
    crit = [m for m in blocks if m.group(1).startswith(':root{color-scheme:')]
    if crit:
        # Replace a stale copy in place, then drop any duplicates. This matters
        # for pages built before build_tools regenerated tools/.critical.css.
        out = text
        for m in reversed(crit[1:]):
            out = out[:m.start()] + out[m.end():]
        first = crit[0]
        current = CRITICAL_CSS.strip()
        if first.group(1).strip() != current:
            out = out[:first.start()] + "<style>" + current + "</style>" + out[first.end():]
        return out
    head = re.search(r'<head[^>]*>([\s\S]*?)</head>', text)
    if not head:
        return text
    candidates = [m.start() for m in re.finditer(
        r'<style\b|<link\b[^>]*rel=["\']stylesheet["\']', head.group(1), re.I)]
    at = head.start(1) + (candidates[0] if candidates else len(head.group(1)))
    return text[:at] + "<style>" + CRITICAL_CSS + "</style>\n" + text[at:]


def replace_header(text: str, path: str) -> str:
    hdr = re.search(r'<header class="masthead"[\s\S]*?</header>', text)
    if hdr:
        start = hdr.start()
        # The 2026 redesign adds a topbar above the masthead; remove both as one
        # block so re-running the sweep replaces rather than duplicates it.
        tb = re.search(r'<div class="topbar"[\s\S]*</div>\s*</div>\s*$', text[:start])
        if tb:
            start = tb.start()
        return text[:start] + chrome_top(path) + text[hdr.end():]
    if '<div class="topbar"' not in text:
        body = re.search(r'<body[^>]*>', text)
        if body:
            return text[:body.end()] + "\n" + chrome_top(path) + text[body.end():]
    return text


def replace_footer(text: str) -> str:
    foot = re.search(r'<footer\b[\s\S]*?</footer>', text)
    if foot:
        return text[:foot.start()] + chrome_footer() + text[foot.end():]
    if "</body>" in text:
        return text.replace("</body>", chrome_footer() + "\n</body>", 1)
    return text


def normalize(text: str, path: str):
    """Return (new_text, dict of what changed)."""
    counts = {"head": 0, "chrome": 0, "footer": 0, "decor": 0, "legacy": 0, "critical": 0}
    out = text

    stripped = DECORATION_DIV.sub("", out)
    stripped = PULSE_DOT.sub("", stripped)
    if stripped != out:
        counts["decor"] = 1
        out = stripped

    stripped = LEGACY_STYLE_BLOCK.sub("", out)
    if stripped != out:
        counts["legacy"] = 1
        out = stripped

    # Strip any leftover pulsing-dot rule from page-specific style blocks.
    stripped = PULSE_RULE.sub("", out)
    if stripped != out:
        counts["legacy"] = 1
        out = stripped

    restored = ensure_critical(out)
    if restored != out:
        counts["critical"] = 1
        out = restored

    head = re.search(r'<head[^>]*>([\s\S]*?)</head>', out)
    if head:
        new_head = insert_head_tags(head.group(1))
        if new_head != head.group(1):
            counts["head"] = 1
            out = out[:head.start(1)] + new_head + out[head.end(1):]

    new_chrome = replace_header(out, path)
    if new_chrome != out:
        counts["chrome"] = 1
        out = new_chrome

    new_footer = replace_footer(out)
    if new_footer != out:
        counts["footer"] = 1
        out = new_footer

    return out, counts


def main() -> int:
    totals = {"files": 0, "changed": 0, "head": 0, "chrome": 0, "footer": 0,
              "decor": 0, "legacy": 0, "critical": 0}
    for path in sorted(ROOT.rglob("*.html")):
        if any(part in SKIP_DIRS for part in path.relative_to(ROOT).parts):
            continue
        totals["files"] += 1
        old = path.read_text(errors="ignore")
        new, counts = normalize(old, url_path(path))
        if new != old:
            path.write_text(new)
            totals["changed"] += 1
            for key in ("head", "chrome", "footer", "decor", "legacy", "critical"):
                totals[key] += counts[key]

    print(
        "sync_chrome: {files} files scanned, {changed} changed "
        "(head {head}, chrome {chrome}, footer {footer}, decorations {decor}, "
        "legacy css {legacy}, critical css {critical})".format(**totals)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
